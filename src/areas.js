export const AREAS = RAW.map(([code, name, lat, lon, jma]) => ({ code, name, lat, lon, jma }));
export const AREA_BY_CODE = new Map(AREAS.map((a) => [a.code, a]));

export function isAreaCode(c) {
  return typeof c === 'string' && AREA_BY_CODE.has(c);
}

function dist2(a, lat, lon) {
  const dx = (a.lon - lon) * Math.cos((lat * Math.PI) / 180);
  const dy = a.lat - lat;
  return dx * dx + dy * dy;
}

/** 緯度経度 → 最寄りの都道府県。座標そのものは保存しない。 */
export function nearestArea(lat, lon) {
  let best = AREAS[0];
  let bd = Infinity;
  for (const a of AREAS) {
    const d = dist2(a, lat, lon);
    if (d < bd) {
      bd = d;
      best = a;
    }
  }
  return best;
}
