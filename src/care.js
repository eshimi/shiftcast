/** 判定に効いた要因の順に、今日の対策を3つ選ぶ。レベルが CARE_MAX_LEVEL より大きいときは null。 */
export function careFor(level, factors = []) {
  if (level > CARE_MAX_LEVEL) return null;
  const order = ['past', 'pressure', 'temp', 'rain', 'hum'].filter((k) => factors.includes(k));
  const tips = [];
  // 各要因の先頭の対策を1つずつ → 足りなければ2つ目、全般で補う
  for (let round = 0; tips.length < 3 && round < 4; round++) {
    for (const k of order) {
      const tip = CARE_FACTORS[k].tips[round];
      if (tip && tips.length < 3 && !tips.some((x) => x.t === tip.t)) tips.push({ ...tip, f: k });
    }
  }
  for (const g of CARE_GENERAL) if (tips.length < 3) tips.push({ ...g, f: 'general' });
  return { tips, factors: order };
}
